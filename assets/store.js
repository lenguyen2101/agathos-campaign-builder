/* -------------------------------------------------------------- FORMATTING */

function esc(s){
  return String(s == null ? '' : s)
    .replace(/&/g,'&amp;').replace(/</g,'&lt;').replace(/>/g,'&gt;').replace(/"/g,'&quot;');
}

function fmtMoney(n){
  return 'S$' + Number(n || 0).toLocaleString('en-SG');
}

/* DD/MM/YYYY — the format the Project / Event tables already use. */
function fmtDate(iso){
  if(!iso) return '';
  var p = iso.slice(0,10).split('-');
  return p[2] + '/' + p[1] + '/' + p[0];
}

function fmtRange(start, end){
  if(!start || !end) return '';
  return fmtDate(start) + ' → ' + fmtDate(end);
}

/* DD/MM/YYYY HH:mm in the reader's own timezone — when a request was raised and
   when it was handled. Date-only fields stay on fmtDate(), which reads the
   stored 'YYYY-MM-DD' as written and never shifts it. */
function fmtDateTime(iso){
  if(!iso) return '';
  var d = new Date(iso);
  var p = function(n){ return (n < 10 ? '0' : '') + n; };
  return p(d.getDate()) + '/' + p(d.getMonth() + 1) + '/' + d.getFullYear()
    + ' ' + p(d.getHours()) + ':' + p(d.getMinutes());
}

function fmtAgo(iso){
  if(!iso) return '';
  var mins = Math.floor((Date.now() - new Date(iso).getTime()) / 60000);
  if(mins < 1)     return 'just now';
  if(mins < 60)    return mins + 'm ago';
  if(mins < 1440)  return Math.floor(mins / 60) + 'h ago';
  if(mins < 10080) return Math.floor(mins / 1440) + 'd ago';
  return fmtDate(iso);
}

/* Status renders as plain uppercase text, like the Project / Event tables. */
function stText(status){
  return '<span class="st ' + status.toLowerCase() + '">' + status.toUpperCase() + '</span>';
}

function toast(msg){
  var el = document.getElementById('toast');
  if(!el) return;
  el.innerHTML = '<span class="ti">' + icon('check', 16) + '</span><span></span>';
  el.lastChild.textContent = msg;
  el.classList.add('show');
  clearTimeout(toast._t);
  toast._t = setTimeout(function(){ el.classList.remove('show'); }, 2600);
}

