/* The hero slide starts as a copy of the campaign page's own hero, then goes
   its own way. Only ever called when the admin switches promoHero on, so
   editing Basics later never overwrites slide copy the admin has since tuned. */
function seedHeroFromBasics(c){
  c.heroEyebrow       = c.heroEyebrow       || c.eyebrow;
  c.heroTitle         = c.heroTitle         || c.name;
  c.heroSubtitle      = c.heroSubtitle      || c.subtitle;
  c.heroBannerDesktop = c.heroBannerDesktop || c.bannerDesktop;
  c.heroBannerMobile  = c.heroBannerMobile  || c.bannerMobile;
  return c;
}

/* What a campaign slide is missing before it can render on the homepage. */
function heroSlideMissing(c){
  var out = [];
  if(!c.heroTitle)         out.push('Slide title');
  if(!c.heroBannerDesktop) out.push('Slide desktop banner');
  return out;
}

function statusOf(c){
  return STATUSES.indexOf(c.status) >= 0 ? c.status : STATUS_DEFAULT;
}

function catItem(id){ return CATALOGUE.filter(function(x){ return x.id === id; })[0] || null; }

/* How many of the referenced items are projects, or events. */
function countKind(items, kind){
  return items.filter(function(id){ var x = catItem(id); return x && x.kind === kind; }).length;
}

function plural(n, word){ return n + ' ' + word + (n === 1 ? '' : 's'); }

/* aboutBody is HTML, so '' and '<p><br></p>' both mean "nothing written". */
function richEmpty(html){
  return !String(html || '').replace(/<[^>]*>/g, '').replace(/&nbsp;/g, ' ').trim();
}

/* '3 projects · 1 event' — the only breakdown of a campaign's items we show. */
function itemMix(items){
  return plural(countKind(items, 'project'), 'project') + ' · ' + plural(countKind(items, 'event'), 'event');
}

/* Campaign total goal = sum of the referenced projects' goals.
   Events have no goal, so they contribute nothing. A campaign made only of
   events therefore totals 0 and has no goal to display. */
function totalGoal(items){
  return items.reduce(function(sum, id){
    var x = catItem(id);
    return sum + (x && x.goal ? x.goal : 0);
  }, 0);
}

/* How many referenced items actually contribute a goal. */
function goalItemCount(items){
  return items.filter(function(id){ var x = catItem(id); return x && x.goal; }).length;
}

function promoLabels(c){
  var out = [];
  if(c.promoHero)   out.push('Homepage hero');
  if(c.promoBanner) out.push('In-project banner');
  return out;
}

/* -------------------------------------------------------------- FORMATTING */

function esc(s){
  return String(s == null ? '' : s)
    .replace(/&/g,'&amp;').replace(/</g,'&lt;').replace(/>/g,'&gt;').replace(/"/g,'&quot;');
}

function fmtMoney(n){
  return 'S$' + Number(n || 0).toLocaleString('en-SG');
}

/* DD/MM/YYYY — the format the Project / Event tables already use. */
function fmtDate(iso){
  if(!iso) return '';
  var p = iso.slice(0,10).split('-');
  return p[2] + '/' + p[1] + '/' + p[0];
}

function fmtRange(start, end){
  if(!start || !end) return '';
  return fmtDate(start) + ' → ' + fmtDate(end);
}

function fmtAgo(iso){
  if(!iso) return '';
  var mins = Math.floor((Date.now() - new Date(iso).getTime()) / 60000);
  if(mins < 1)     return 'just now';
  if(mins < 60)    return mins + 'm ago';
  if(mins < 1440)  return Math.floor(mins / 60) + 'h ago';
  if(mins < 10080) return Math.floor(mins / 1440) + 'd ago';
  return fmtDate(iso);
}

/* Status renders as plain uppercase text, like the Project / Event tables. */
function stText(status){
  return '<span class="st ' + status.toLowerCase() + '">' + status.toUpperCase() + '</span>';
}

function toast(msg){
  var el = document.getElementById('toast');
  if(!el) return;
  el.innerHTML = '<span class="ti">' + icon('check', 16) + '</span><span></span>';
  el.lastChild.textContent = msg;
  el.classList.add('show');
  clearTimeout(toast._t);
  toast._t = setTimeout(function(){ el.classList.remove('show'); }, 2600);
}

/* ============================================================================
   HOMEPAGE HERO — second backend boundary

     getHero()          GET   /admin/homepage-hero   -> HeroConfig
     saveHero(cfg)      PUT   /admin/homepage-hero   -> HeroConfig

   HeroConfig
   ----------
     defaultSlide  { eyebrow, title, subtitle, bannerDesktop, bannerMobile, ctaLabel }
     order         string[]   'default' plus campaign IDs, in carousel order

   Neither campaign slides nor free slides are stored here. heroSlides() joins
   the stored order against the campaigns that currently have promoHero on and
   against the free slides, so each record stays the single source of truth for
   its own copy. Anything in `order` that no longer qualifies is skipped, and
   anything new is appended — the stored order self-heals rather than going
   stale.
   ============================================================================ */

var HERO_KEY = 'agathos.hero.v2';

